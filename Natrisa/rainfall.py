# เกณฑ์ปริมาณฝน (มม.) ตามกรมอุตุนิยมวิทยา https://www.tmd.go.th/info/เกณฑ์อากาศ (ตรวจเมื่อ 12 ต.ค. 2569)
#   ฝนเล็กน้อย 0.1-10.0 | ปานกลาง 10.1-35.0 | หนัก 35.1-90.0 | หนักมาก 90.1 ขึ้นไป
# หมายเหตุ: หน้าเว็บ TMD ไม่ได้ระบุช่วงเวลาไว้ชัด ระบบนี้นำไปใช้กับฝนรวม 24 ชม.
RAIN_THRESHOLDS_MM = {"ปานกลาง": 10.0, "หนัก": 35.0, "หนักมาก": 90.0}


def classify_rain_24h(mm):
    """จำแนกระดับฝนจากปริมาณฝน 24 ชม. (มม.)"""
    if mm is None:
        return None
    if mm > RAIN_THRESHOLDS_MM["หนักมาก"]:
        return "ฝนหนักมาก"
    if mm > RAIN_THRESHOLDS_MM["หนัก"]:
        return "ฝนหนัก"
    if mm > RAIN_THRESHOLDS_MM["ปานกลาง"]:
        return "ฝนปานกลาง"
    if mm >= 0.1:
        return "ฝนเล็กน้อย"
    return "ไม่มีฝน"


def is_high_rain(level):
    return level in ("ฝนหนัก", "ฝนหนักมาก")


